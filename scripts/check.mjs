// Guardrails and repo map. Usage: node scripts/check.mjs [--map-only]
// Fails (exit 1) on: missing header, stray hex colors, forbidden imports.
// Warns (exit 0) on: `any` in a type position.
// Always rewrites docs/MAP.md so the agent can find files without scanning the repo.
import fs from 'fs';
import path from 'path';

const ROOT = process.cwd(), SRC = path.join(ROOT, 'src');
const mapOnly = process.argv.includes('--map-only');
const errors = [], warns = [], rows = [];
const rel = f => path.relative(ROOT, f).split(path.sep).join('/');
const walk = d => fs.existsSync(d) ? fs.readdirSync(d, { withFileTypes: true }).flatMap(e => e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]) : [];
const files = walk(SRC).filter(f => /\.(ts|astro)$/.test(f) && !f.endsWith('.d.ts')).sort();

for (const f of files) {
  const s = fs.readFileSync(f, 'utf8'), r = rel(f);
  const head = (s.match(/\/\*\*[\s\S]*?\*\//) || [''])[0];
  const desc = ((head.match(/@module\s+([^\n*]+)/) || [, ''])[1] || '').trim();
  const imports = [...s.matchAll(/from\s+['"]([^'"]+)['"]/g)].map(m => m[1]).filter(i => i.startsWith('.') || i.startsWith('@/'));
  const exps = [...s.matchAll(/export\s+(?:default\s+)?(?:async\s+)?(?:const|function|class|type|interface|enum)\s+(\w+)/g)].map(m => m[1]);
  const target = i => i.startsWith('@/') ? 'src/' + i.slice(2) : rel(path.resolve(path.dirname(f), i));
  rows.push({ r, desc, exps, uses: imports.map(target) });

  if (!desc) errors.push(`${r}: missing header "/** @module name: purpose */"`);
  const code = s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/.*$/gm, '$1');
  if (f.endsWith('.ts') && r !== 'src/config/palette.ts' && /#[0-9a-fA-F]{6}\b/.test(code)) errors.push(`${r}: hex color outside src/config/palette.ts. Use a palette token.`);
  if (/:\s*any\b|\bas any\b/.test(code)) warns.push(`${r}: uses "any"`);

  for (const i of imports) {
    const t = target(i);
    if (r.startsWith('src/config/') && !t.startsWith('src/config/')) errors.push(`${r}: config may not import ${i}`);
    if (r.startsWith('src/scene/') && /^src\/(ui|sections|pages)\//.test(t)) errors.push(`${r}: scene may not import ${i}`);
    if (r.startsWith('src/ui/') && t.startsWith('src/scene/') && !/^src\/scene\/api(\.ts)?$/.test(t)) errors.push(`${r}: ui may reach the scene only through src/scene/api.ts (found ${i})`);
    const a = r.match(/^src\/scene\/rooms\/([^/]+)\//), b = t.match(/^src\/scene\/rooms\/([^/]+)(?:\/|$)/);
    if (a && a[1] !== 'props' && b && b[1] !== a[1] && b[1] !== 'props' && !b[1].includes('.')) errors.push(`${r}: room "${a[1]}" may not import room "${b[1]}"`);
  }
}

const groups = {};
for (const x of rows) (groups[x.r.split('/').slice(0, -1).join('/')] ||= []).push(x);
let md = '# MAP (generated by scripts/check.mjs; do not edit)\n\nSearch this file before creating anything.\n';
for (const g of Object.keys(groups).sort()) {
  md += `\n## ${g}/\n`;
  for (const x of groups[g]) md += `- ${path.basename(x.r)}: ${x.desc || '(no header)'}${x.exps.length ? `\n  exports: ${x.exps.join(', ')}` : ''}${x.uses.length ? `\n  uses: ${x.uses.join(', ')}` : ''}\n`;
}
fs.mkdirSync(path.join(ROOT, 'docs'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'docs/MAP.md'), md);

if (mapOnly) { console.log(`MAP written for ${rows.length} files.`); process.exit(0); }
errors.forEach(e => console.error('ERROR ' + e));
warns.forEach(w => console.warn('WARN  ' + w));
if (errors.length) {
  console.error(`\n${errors.length} error(s). Fix them, then run again.`);
  process.exit(1);
}
console.log(`\nOK: ${rows.length} files checked.${warns.length ? ` ${warns.length} warning(s).` : ''}`);
